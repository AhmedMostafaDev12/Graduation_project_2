def _secure_tables() -> None:
    """Roles, grants and RLS (spec D25, docs/DATABASE.md §2).

    The table owner (postgres on Supabase, remori locally) bypasses RLS. remori_app
    (API + workers) gets full row access, remori_readonly can only read. Supabase's
    anon/authenticated roles have no policy, so they see nothing.
    """
    op.execute(
        """
        DO $$
        BEGIN
          IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'remori_app') THEN
            CREATE ROLE remori_app NOLOGIN;
          END IF;
          IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'remori_readonly') THEN
            CREATE ROLE remori_readonly NOLOGIN;
          END IF;
        END
        $$;
        """
    )
    op.execute("GRANT USAGE ON SCHEMA public TO remori_app, remori_readonly")
    op.execute("ALTER TABLE alembic_version ENABLE ROW LEVEL SECURITY")
    for table in TABLES:
        op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO remori_app")
        op.execute(f"GRANT SELECT ON {table} TO remori_readonly")
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY remori_app_all ON {table} FOR ALL TO remori_app "
            "USING (true) WITH CHECK (true)"
        )
        op.execute(
            f"CREATE POLICY remori_readonly_select ON {table} FOR SELECT TO remori_readonly "
            "USING (true)"
        )


